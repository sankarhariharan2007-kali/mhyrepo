-- Steam refund policy: < 120 minutes played, purchased within 14 days, paid titles only.
CREATE OR REPLACE FUNCTION fn_order_items_steam_refund_policy() RETURNS trigger AS $$
DECLARE
    v_user_id      INT;
    v_purchased_at TIMESTAMP;
    v_playtime     INT;
BEGIN
    IF OLD.status = 'refunded' AND NEW.status <> 'refunded' THEN
        RAISE EXCEPTION 'A refunded order item cannot be reverted';
    END IF;

    IF OLD.status <> 'refunded' AND NEW.status = 'refunded' THEN
        SELECT user_id, created_at INTO v_user_id, v_purchased_at
        FROM orders WHERE order_id = NEW.order_id;

        SELECT MAX(playtime_minutes) INTO v_playtime
        FROM user_library WHERE user_id = v_user_id AND game_id = NEW.game_id;

        IF NEW.price_at_purchase <= 0 THEN
            RAISE EXCEPTION 'Steam refund policy: free titles cannot be refunded';
        END IF;
        IF v_playtime IS NULL THEN
            RAISE EXCEPTION 'Steam refund policy: game is not owned in user library';
        END IF;
        IF v_playtime >= 120 THEN
            RAISE EXCEPTION 'Steam 2-hour refund policy: playtime must be less than 120 minutes';
        END IF;
        IF EXTRACT(EPOCH FROM (NOW() - v_purchased_at)) > 1209600 THEN
            RAISE EXCEPTION 'Steam refund policy: purchase must be within 14 days';
        END IF;
        IF NEW.refunded_at IS NULL THEN
            NEW.refunded_at := NOW();
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_order_items_steam_refund_policy ON order_items;
CREATE TRIGGER trg_order_items_steam_refund_policy
    BEFORE UPDATE ON order_items
    FOR EACH ROW EXECUTE FUNCTION fn_order_items_steam_refund_policy();

