-- Upgrade databases created before roles existed. Safe to run on every boot.
ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'user';
ALTER TABLE users ADD COLUMN IF NOT EXISTS publisher_id INT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS region_id INT NULL;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'fk_users_publisher' AND conrelid = 'users'::regclass) THEN
        ALTER TABLE users ADD CONSTRAINT fk_users_publisher FOREIGN KEY (publisher_id)
            REFERENCES publishers(publisher_id) ON UPDATE CASCADE ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'fk_users_region' AND conrelid = 'users'::regclass) THEN
        ALTER TABLE users ADD CONSTRAINT fk_users_region FOREIGN KEY (region_id)
            REFERENCES regions(region_id) ON UPDATE CASCADE ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'chk_users_role' AND conrelid = 'users'::regclass) THEN
        ALTER TABLE users ADD CONSTRAINT chk_users_role
            CHECK (role IN ('user', 'publisher', 'admin'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS friendships (
    user_id    INT NOT NULL,
    friend_id  INT NOT NULL,
    status     VARCHAR(50) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, friend_id),
    CONSTRAINT fk_friendships_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_friendships_friend FOREIGN KEY (friend_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE OR REPLACE FUNCTION fn_friendships_no_self() RETURNS trigger AS $$
BEGIN
    IF NEW.user_id = NEW.friend_id THEN
        RAISE EXCEPTION 'A user cannot add themselves as a friend';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_friendships_no_self ON friendships;
CREATE TRIGGER trg_friendships_no_self
    BEFORE INSERT ON friendships
    FOR EACH ROW EXECUTE FUNCTION fn_friendships_no_self();

