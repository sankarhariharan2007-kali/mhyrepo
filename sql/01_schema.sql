-- SAUNA: digital game store, PostgreSQL schema (19 tables, multi-currency + refund policy)
-- Idempotent: safe to run on every boot (CREATE IF NOT EXISTS + ALTER ... IF NOT EXISTS upgrades).

-- Normalized ISO 4217 currency lookup; rates are quoted from the base currency INR.
CREATE TABLE IF NOT EXISTS currencies (
    currency_code CHAR(3) PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    symbol        VARCHAR(10) NOT NULL,
    minor_units   SMALLINT NOT NULL DEFAULT 2,
    rate_from_inr NUMERIC(12, 6) NOT NULL,
    CONSTRAINT chk_currencies_minor_units CHECK (minor_units BETWEEN 0 AND 4),
    CONSTRAINT chk_currencies_rate CHECK (rate_from_inr > 0)
);

-- Normalized country -> currency lookup.
CREATE TABLE IF NOT EXISTS regions (
    region_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_name  VARCHAR(100) NOT NULL UNIQUE,
    country_code  CHAR(2) NOT NULL UNIQUE,
    currency_code CHAR(3) NOT NULL,
    CONSTRAINT fk_regions_currency FOREIGN KEY (currency_code) REFERENCES currencies(currency_code)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

