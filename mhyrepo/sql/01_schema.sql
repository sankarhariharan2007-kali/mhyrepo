-- SAUNA: digital game store, PostgreSQL schema (17 tables from steam_er_diagram.png)

CREATE TABLE IF NOT EXISTS publishers (
    publisher_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    country      VARCHAR(100),
    founded_year INT,
    website      VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS developers (
    developer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    country      VARCHAR(100),
    website      VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS games (
    game_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(255) NOT NULL,
    description  TEXT,
    release_date DATE,
    base_price   NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    publisher_id INT NOT NULL,
    developer_id INT NOT NULL,
    age_rating   VARCHAR(50),
    CONSTRAINT fk_games_publisher FOREIGN KEY (publisher_id) REFERENCES publishers(publisher_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_games_developer FOREIGN KEY (developer_id) REFERENCES developers(developer_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_games_base_price CHECK (base_price >= 0)
);
CREATE INDEX IF NOT EXISTS idx_games_title ON games(title);
CREATE INDEX IF NOT EXISTS idx_games_publisher ON games(publisher_id);
CREATE INDEX IF NOT EXISTS idx_games_developer ON games(developer_id);

CREATE TABLE IF NOT EXISTS users (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(100) NOT NULL UNIQUE,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20) NOT NULL DEFAULT 'user',
    publisher_id   INT NULL,
    wallet_balance NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    country        VARCHAR(100),
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_wallet CHECK (wallet_balance >= 0)
);

-- Upgrade databases created before roles existed. Safe to run on every boot.
ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'user';
ALTER TABLE users ADD COLUMN IF NOT EXISTS publisher_id INT NULL;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'fk_users_publisher' AND conrelid = 'users'::regclass) THEN
        ALTER TABLE users ADD CONSTRAINT fk_users_publisher FOREIGN KEY (publisher_id)
            REFERENCES publishers(publisher_id) ON UPDATE CASCADE ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'chk_users_role' AND conrelid = 'users'::regclass) THEN
        ALTER TABLE users ADD CONSTRAINT chk_users_role
            CHECK (role IN ('user', 'publisher', 'admin'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS friendships (
    user_id    INT NOT NULL,
    friend_id  INT NOT NULL,
    status     VARCHAR(50) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, friend_id),
    CONSTRAINT fk_friendships_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_friendships_friend FOREIGN KEY (friend_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE OR REPLACE FUNCTION fn_friendships_no_self() RETURNS trigger AS $$
BEGIN
    IF NEW.user_id = NEW.friend_id THEN
        RAISE EXCEPTION 'A user cannot add themselves as a friend';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_friendships_no_self ON friendships;
CREATE TRIGGER trg_friendships_no_self
    BEFORE INSERT ON friendships
    FOR EACH ROW EXECUTE FUNCTION fn_friendships_no_self();

CREATE TABLE IF NOT EXISTS orders (
    order_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INT NOT NULL,
    total_amount   NUMERIC(10, 2) NOT NULL,
    payment_method VARCHAR(50) NOT NULL,
    status         VARCHAR(50) NOT NULL DEFAULT 'completed',
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_orders_total CHECK (total_amount >= 0)
);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);

CREATE TABLE IF NOT EXISTS wallet_transactions (
    txn_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            INT NOT NULL,
    amount             NUMERIC(10, 2) NOT NULL,
    txn_type           VARCHAR(50) NOT NULL,
    reference_order_id INT NULL,
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wallet_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_wallet_order FOREIGN KEY (reference_order_id) REFERENCES orders(order_id)
        ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_wallet_user ON wallet_transactions(user_id);

CREATE TABLE IF NOT EXISTS order_items (
    order_item_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          INT NOT NULL,
    game_id           INT NOT NULL,
    price_at_purchase NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(order_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_order_items_game FOREIGN KEY (game_id) REFERENCES games(game_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_order_item_price CHECK (price_at_purchase >= 0),
    CONSTRAINT uq_order_game UNIQUE (order_id, game_id)
);

CREATE TABLE IF NOT EXISTS user_library (
    user_id          INT NOT NULL,
    game_id          INT NOT NULL,
    acquired_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    playtime_minutes INT NOT NULL DEFAULT 0,
    last_played_at   TIMESTAMP NULL,
    PRIMARY KEY (user_id, game_id),
    CONSTRAINT fk_library_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_library_game FOREIGN KEY (game_id) REFERENCES games(game_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_library_playtime CHECK (playtime_minutes >= 0)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            INT NOT NULL,
    game_id            INT NOT NULL,
    is_recommended     BOOLEAN NOT NULL,
    review_text        TEXT,
    playtime_at_review INT NOT NULL DEFAULT 0,
    helpful_votes      INT NOT NULL DEFAULT 0,
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_reviews_game FOREIGN KEY (game_id) REFERENCES games(game_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_review_user_game UNIQUE (user_id, game_id)
);
CREATE INDEX IF NOT EXISTS idx_reviews_game ON reviews(game_id);

CREATE TABLE IF NOT EXISTS wishlist (
    user_id  INT NOT NULL,
    game_id  INT NOT NULL,
    added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, game_id),
    CONSTRAINT fk_wishlist_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_game FOREIGN KEY (game_id) REFERENCES games(game_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sales (
    sale_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(255) NOT NULL,
    start_date TIMESTAMP NOT NULL,
    end_date   TIMESTAMP NOT NULL,
    CONSTRAINT chk_sales_dates CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS sale_items (
    sale_id      INT NOT NULL,
    game_id      INT NOT NULL,
    discount_pct INT NOT NULL,
    PRIMARY KEY (sale_id, game_id),
    CONSTRAINT fk_sale_items_sale FOREIGN KEY (sale_id) REFERENCES sales(sale_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_sale_items_game FOREIGN KEY (game_id) REFERENCES games(game_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_sale_discount CHECK (discount_pct BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS achievements (
    achievement_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id        INT NOT NULL,
    name           VARCHAR(255) NOT NULL,
    description    TEXT,
    is_hidden      BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_achievements_game FOREIGN KEY (game_id) REFERENCES games(game_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_achievements_game ON achievements(game_id);

CREATE TABLE IF NOT EXISTS user_achievements (
    user_id        INT NOT NULL,
    achievement_id INT NOT NULL,
    unlocked_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, achievement_id),
    CONSTRAINT fk_user_ach_user FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_user_ach_achievement FOREIGN KEY (achievement_id) REFERENCES achievements(achievement_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tags (
    tag_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS game_tags (
    game_id INT NOT NULL,
    tag_id  INT NOT NULL,
    PRIMARY KEY (game_id, tag_id),
    CONSTRAINT fk_game_tags_game FOREIGN KEY (game_id) REFERENCES games(game_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_game_tags_tag FOREIGN KEY (tag_id) REFERENCES tags(tag_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
